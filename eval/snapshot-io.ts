/**
 * Writes the bundled persona snapshots (personas/snapshots) and the proof
 * summary both eval/record-demo.ts and eval/reproof.ts print.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Plan, ProofSide } from "../lib/contract";
import { proofRows } from "../lib/agent/proof-rows";
import type { PersonaSnapshot } from "../personas/snapshots";

export const SNAPSHOT_DIR = "personas/snapshots";

export function writeSnapshot(snap: PersonaSnapshot, by = "eval/record-demo.ts"): void {
  writeFileSync(
    join(SNAPSHOT_DIR, `${snap.personaId}.ts`),
    `/** Generated by ${by} (${snap.recordedAt}${snap.qlooMock ? ", Qloo mocked" : ""}); do not edit. */\nimport type { PersonaSnapshot } from "./types";\n\nexport default JSON.parse(${JSON.stringify(JSON.stringify(snap))}) as PersonaSnapshot;\n`,
  );
  const ids = readdirSync(SNAPSHOT_DIR).filter((f) => f.endsWith(".ts") && !["index.ts", "types.ts"].includes(f)).map((f) => f.slice(0, -3)).sort();
  const ident = (id: string) => id.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c: string | undefined) => (c ?? "").toUpperCase());
  writeFileSync(
    join(SNAPSHOT_DIR, "index.ts"),
    [
      "/** Generated by eval/record-demo.ts: the bundled persona snapshots. */",
      ...ids.map((id) => `import ${ident(id)} from "./${id}";`),
      'import type { PersonaSnapshot } from "./types";',
      "",
      'export type { PersonaSnapshot } from "./types";',
      `export const SNAPSHOTS: Record<string, PersonaSnapshot> = {${ids.map((id) => ` ${JSON.stringify(id)}: ${ident(id)}`).join(",")}${ids.length ? " " : ""}};`,
      "",
    ].join("\n"),
  );
}

/** The proof rows as the paper orders them (lib/agent/proof-rows.ts), plus the hero bridge. */
export function printProof(plan: Plan, theirs: ProofSide | undefined, theirsRuns?: ProofSide[]): void {
  if (plan.proof && theirs) {
    const runs = theirsRuns && theirsRuns.length > 1 ? `, ${theirsRuns.length} runs` : "";
    const branch = theirs.nearestBranch ? "its picks at their nearest branch" : "its picks by name match, not the nearest branch";
    console.log(`  proof (ours / model alone${runs}; ${branch}):`);
    for (const r of proofRows(plan.proof, theirs, theirsRuns)) console.log(`  ${r.label.padEnd(14)} ${r.ours} / ${r.theirs}${r.note ? `   (${r.note})` : ""}`);
  } else console.log("  proof: missing on one side");
  if (plan.heroBridge) console.log(`  hero bridge: ${plan.heroBridge.text}`);
}
